#!/usr/bin/env node
// Build an icon set into ready-to-use packages. Icons with lint errors are refused (use --force to include them).
// Usage: node scripts/build.mjs <folder> [--out dist] [--formats svg,sprite,react,vue,element,json,preview]
//        [--prefix icon-] [--name MySet] [--typescript]
// Output (per format):
//   svg/      optimized files            sprite.svg   <symbol id="icon-name"> for <use href="sprite.svg#icon-name">
//   react/    index.js + index.d.ts      vue/         index.js + index.d.ts
//   element/  <zoro-icon name="…">       icons.json   { name: { body, viewBox } } (Iconify-style)
//   preview.html  searchable gallery with copy buttons, size and dark-mode switches
// Components are accessible by default: aria-hidden unless a `title` prop is given (then role="img" + label).
import fs from "node:fs";
import path from "node:path";
import { isMain, parseArgs, usageOf } from "./lib/args.mjs";
import { lint } from "./lint.mjs";
import { loadSet } from "./lib/set.mjs";
import { optimize, parseSvg, stringifySvg } from "./lib/vendor/svgo.mjs";

export const FORMATS = ["svg", "sprite", "react", "vue", "element", "json", "preview"];

/** "arrow-left" → "ArrowLeft" (component name); digits first get a prefix. */
export const pascal = (s) => {
  const p = s.replace(/(^|[-_\s]+)([a-z0-9])/gi, (_, __, c) => c.toUpperCase());
  return /^\d/.test(p) ? `Icon${p}` : p;
};

/** One icon as { viewBox, attrs (root presentation attributes), body (inner markup, ids prefixed) }. */
export function parts(text, name) {
  const optimized = optimize(text, {
    multipass: true,
    floatPrecision: 3,
    plugins: [{ name: "preset-default", params: { overrides: { removeUnknownsAndDefaults: { keepRoleAttr: true } } } }, { name: "prefixIds", params: { prefix: `${name}-`, delim: "" } }, "removeDimensions"],
  }).data;
  const ast = parseSvg(optimized);
  const root = ast.children.find((c) => c.type === "element" && c.name === "svg");
  const { viewBox = "0 0 24 24", xmlns, "xmlns:xlink": _x, ...attrs } = root.attributes;
  const body = root.children.map((c) => stringifySvg({ type: "root", children: [c] })).join("");
  return { viewBox, attrs, body };
}

const attrString = (attrs) => Object.entries(attrs).map(([k, v]) => `${k}="${String(v).replace(/"/g, "&quot;")}"`).join(" ");
const camel = (k) => (k.startsWith("aria-") || k.startsWith("data-") ? k : k.replace(/[-:]([a-z])/g, (_, c) => c.toUpperCase()));

export function buildSet(set, { out, formats = FORMATS, prefix = "icon-", name = "Icons", force = false, log = console.log } = {}) {
  const results = lint(set);
  const errors = new Map();
  for (const r of results.filter((x) => x.severity === "error")) for (const f of r.findings) errors.set(f.name, `${r.id}: ${f.detail}`);
  const icons = set.icons.filter((i) => i.svg.ok && (force || !errors.has(i.name)));
  for (const [n, why] of errors) if (!force) log(`refused ${n} (${why})`);
  if (!icons.length) throw new Error("no icons to build");
  const data = icons.map((i) => ({ name: i.name, component: pascal(i.name), ...parts(i.text, i.name) }));
  const seen = new Map();
  for (const d of data) {
    if (seen.has(d.component)) throw new Error(`"${d.name}" and "${seen.get(d.component)}" both become component ${d.component}; rename one`);
    seen.set(d.component, d.name);
  }
  fs.mkdirSync(out, { recursive: true });
  const write = (rel, text) => {
    const f = path.join(out, rel);
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, text);
  };
  const svgOf = (d, extra = "") => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${d.viewBox}" ${attrString(d.attrs)}${extra}>${d.body}</svg>`;

  if (formats.includes("svg")) for (const d of data) write(`svg/${d.name}.svg`, svgOf(d) + "\n");

  if (formats.includes("sprite"))
    write(
      "sprite.svg",
      `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${data.map((d) => `<symbol id="${prefix}${d.name}" viewBox="${d.viewBox}" ${attrString(d.attrs)}>${d.body}</symbol>`).join("\n")}\n</svg>\n`,
    );

  if (formats.includes("json")) write("icons.json", JSON.stringify({ prefix: prefix.replace(/-$/, ""), icons: Object.fromEntries(data.map((d) => [d.name, { viewBox: d.viewBox, attrs: d.attrs, body: d.body }])) }, null, 2) + "\n");

  if (formats.includes("react")) {
    const lines = [
      `// Generated by zoro-icons. ${data.length} icons. Usage: <${data[0].component} size={20} title="optional label" />`,
      `import { createElement, forwardRef } from "react";`,
      ``,
      `function make(displayName, attrs, body) {`,
      `  const C = forwardRef(function Icon({ size = 24, title, ...props }, ref) {`,
      `    const a11y = title ? { role: "img", "aria-label": title } : { "aria-hidden": true };`,
      `    return createElement("svg", { xmlns: "http://www.w3.org/2000/svg", width: size, height: size, ...attrs, ...a11y, ...props, ref, dangerouslySetInnerHTML: { __html: (title ? "<title>" + title.replace(/[<&]/g, (c) => (c === "<" ? "&lt;" : "&amp;")) + "</title>" : "") + body } });`,
      `  });`,
      `  C.displayName = displayName;`,
      `  return C;`,
      `}`,
      ``,
      ...data.map((d) => `export const ${d.component} = make(${JSON.stringify(d.component)}, ${JSON.stringify(Object.fromEntries([["viewBox", d.viewBox], ...Object.entries(d.attrs).map(([k, v]) => [camel(k), v])]))}, ${JSON.stringify(d.body)});`),
      ``,
      `export const icons = { ${data.map((d) => `${JSON.stringify(d.name)}: ${d.component}`).join(", ")} };`,
      ``,
    ];
    write("react/index.js", lines.join("\n"));
    write(
      "react/index.d.ts",
      `import type { ForwardRefExoticComponent, RefAttributes, SVGProps } from "react";\nexport interface IconProps extends Omit<SVGProps<SVGSVGElement>, "ref"> {\n  /** Width and height in px (default 24). */\n  size?: number | string;\n  /** Accessible name. Without it the icon is decorative (aria-hidden). */\n  title?: string;\n}\nexport type Icon = ForwardRefExoticComponent<IconProps & RefAttributes<SVGSVGElement>>;\n${data.map((d) => `export declare const ${d.component}: Icon;`).join("\n")}\nexport declare const icons: Record<${data.map((d) => JSON.stringify(d.name)).join(" | ")}, Icon>;\n`,
    );
  }

  if (formats.includes("vue")) {
    write(
      "vue/index.js",
      [
        `// Generated by zoro-icons. ${data.length} icons. Usage: <${data[0].component} :size="20" title="optional label" />`,
        `import { defineComponent, h } from "vue";`,
        ``,
        `function make(name, attrs, body) {`,
        `  return defineComponent({`,
        `    name,`,
        `    props: { size: { type: [Number, String], default: 24 }, title: { type: String, default: undefined } },`,
        `    setup(props) {`,
        `      return () => {`,
        `        const a11y = props.title ? { role: "img", "aria-label": props.title } : { "aria-hidden": "true" };`,
        `        const t = props.title ? "<title>" + props.title.replace(/[<&]/g, (c) => (c === "<" ? "&lt;" : "&amp;")) + "</title>" : "";`,
        `        return h("svg", { xmlns: "http://www.w3.org/2000/svg", width: props.size, height: props.size, ...attrs, ...a11y, innerHTML: t + body });`,
        `      };`,
        `    },`,
        `  });`,
        `}`,
        ``,
        ...data.map((d) => `export const ${d.component} = make(${JSON.stringify(d.component)}, ${JSON.stringify({ viewBox: d.viewBox, ...d.attrs })}, ${JSON.stringify(d.body)});`),
        ``,
        `export const icons = { ${data.map((d) => `${JSON.stringify(d.name)}: ${d.component}`).join(", ")} };`,
        ``,
      ].join("\n"),
    );
    write("vue/index.d.ts", `import type { DefineComponent } from "vue";\nexport type Icon = DefineComponent<{ size?: number | string; title?: string }>;\n${data.map((d) => `export declare const ${d.component}: Icon;`).join("\n")}\nexport declare const icons: Record<string, Icon>;\n`);
  }

  if (formats.includes("element"))
    write(
      "element/zoro-icon.js",
      [
        `// Generated by zoro-icons. <script type="module" src="zoro-icon.js"></script> then <zoro-icon name="${data[0].name}" size="20" label="optional"></zoro-icon>`,
        `const ICONS = ${JSON.stringify(Object.fromEntries(data.map((d) => [d.name, [d.viewBox, attrString(d.attrs), d.body]])))};`,
        `class ZoroIcon extends HTMLElement {`,
        `  static observedAttributes = ["name", "size", "label"];`,
        `  connectedCallback() { this.render(); }`,
        `  attributeChangedCallback() { this.render(); }`,
        `  render() {`,
        `    const icon = ICONS[this.getAttribute("name")];`,
        `    if (!icon) { this.innerHTML = ""; return; }`,
        `    const size = this.getAttribute("size") || "24";`,
        `    const label = this.getAttribute("label");`,
        `    const esc = (s) => s.replace(/[<&"]/g, (c) => ({ "<": "&lt;", "&": "&amp;", '"': "&quot;" })[c]);`,
        `    const a11y = label ? 'role="img" aria-label="' + esc(label) + '"' : 'aria-hidden="true"';`,
        `    this.style.display = "inline-flex";`,
        `    this.innerHTML = '<svg xmlns="http://www.w3.org/2000/svg" width="' + esc(size) + '" height="' + esc(size) + '" viewBox="' + icon[0] + '" ' + icon[1] + " " + a11y + ">" + (label ? "<title>" + esc(label) + "</title>" : "") + icon[2] + "</svg>";`,
        `  }`,
        `}`,
        `if (!customElements.get("zoro-icon")) customElements.define("zoro-icon", ZoroIcon);`,
        ``,
      ].join("\n"),
    );

  if (formats.includes("preview")) write("preview.html", previewHtml(data, { name }));

  log(`built ${data.length} icons (${formats.join(", ")}) → ${out}`);
  return { built: data.map((d) => d.name), refused: force ? [] : [...errors.keys()] };
}

function previewHtml(data, { name }) {
  const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/"/g, "&quot;");
  const cells = data
    .map((d) => `<button class="i" data-name="${esc(d.name)}" title="${esc(d.name)}"><svg xmlns="http://www.w3.org/2000/svg" viewBox="${d.viewBox}" ${attrString(d.attrs)} aria-hidden="true">${d.body}</svg><span>${esc(d.name)}</span></button>`)
    .join("\n");
  const src = JSON.stringify(Object.fromEntries(data.map((d) => [d.name, `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="${d.viewBox}" ${attrString(d.attrs)}>${d.body}</svg>`])));
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(name)} — ${data.length} icons</title>
<style>
  :root { --bg: #fafafa; --card: #fff; --fg: #18181b; --muted: #71717a; --line: #e4e4e7; --accent: #2563eb; color-scheme: light; }
  :root[data-theme="dark"] { --bg: #0f1012; --card: #18191c; --fg: #f4f4f5; --muted: #a1a1aa; --line: #2a2b30; --accent: #60a5fa; color-scheme: dark; }
  @media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) { --bg: #0f1012; --card: #18191c; --fg: #f4f4f5; --muted: #a1a1aa; --line: #2a2b30; --accent: #60a5fa; color-scheme: dark; } }
  * { box-sizing: border-box; }
  body { margin: 0; background: var(--bg); color: var(--fg); font: 14px/1.5 ui-sans-serif, system-ui, sans-serif; }
  header { position: sticky; top: 0; z-index: 1; display: flex; flex-wrap: wrap; gap: 12px; align-items: center; padding: 12px 16px; background: var(--bg); border-bottom: 1px solid var(--line); }
  h1 { margin: 0 auto 0 0; font-size: 16px; }
  input[type=search] { min-width: 0; flex: 1 1 200px; max-width: 320px; padding: 8px 10px; border: 1px solid var(--line); border-radius: 8px; background: var(--card); color: var(--fg); font: inherit; }
  label { display: inline-flex; gap: 6px; align-items: center; color: var(--muted); }
  .btn { padding: 7px 10px; border: 1px solid var(--line); border-radius: 8px; background: var(--card); color: var(--fg); font: inherit; cursor: pointer; }
  main { display: grid; grid-template-columns: repeat(auto-fill, minmax(104px, 1fr)); gap: 8px; padding: 16px; }
  .i { display: grid; justify-items: center; gap: 8px; padding: 16px 6px 10px; border: 1px solid var(--line); border-radius: 10px; background: var(--card); color: var(--fg); cursor: pointer; font: inherit; }
  .i:hover { border-color: var(--accent); }
  .i:focus-visible { outline: 2px solid var(--accent); outline-offset: 2px; }
  .i svg { width: var(--size, 24px); height: var(--size, 24px); }
  .i span { max-width: 100%; overflow: hidden; text-overflow: ellipsis; white-space: nowrap; font-size: 12px; color: var(--muted); }
  #toast { position: fixed; bottom: 16px; left: 50%; transform: translateX(-50%); padding: 8px 14px; border-radius: 8px; background: var(--fg); color: var(--bg); opacity: 0; transition: opacity .15s; pointer-events: none; }
  #toast.on { opacity: 1; }
  @media (prefers-reduced-motion: reduce) { #toast { transition: none; } }
</style>
</head>
<body>
<header>
  <h1>${esc(name)} <span style="color:var(--muted);font-weight:400">${data.length} icons</span></h1>
  <input type="search" id="q" placeholder="Search icons" aria-label="Search icons">
  <label>Size <input type="range" id="size" min="12" max="64" value="24" aria-label="Icon size"> <output id="sv">24</output></label>
  <button class="btn" id="theme" type="button">Theme</button>
</header>
<main id="grid">
${cells}
</main>
<div id="toast" role="status" aria-live="polite"></div>
<script>
  const SRC = ${src};
  const grid = document.getElementById("grid"), q = document.getElementById("q"), size = document.getElementById("size");
  q.addEventListener("input", () => { const t = q.value.trim().toLowerCase(); for (const b of grid.children) b.hidden = t && !b.dataset.name.includes(t); });
  size.addEventListener("input", () => { grid.style.setProperty("--size", size.value + "px"); document.getElementById("sv").value = size.value; });
  document.getElementById("theme").addEventListener("click", () => { const r = document.documentElement; r.dataset.theme = r.dataset.theme === "dark" ? "light" : "dark"; });
  const toast = document.getElementById("toast");
  grid.addEventListener("click", async (e) => {
    const b = e.target.closest(".i"); if (!b) return;
    try { await navigator.clipboard.writeText(SRC[b.dataset.name]); toast.textContent = "Copied " + b.dataset.name + ".svg"; }
    catch { toast.textContent = b.dataset.name; }
    toast.classList.add("on"); setTimeout(() => toast.classList.remove("on"), 1200);
  });
</script>
</body>
</html>
`;
}

export async function main(argv = process.argv.slice(2)) {
  const a = parseArgs(argv);
  if (!a._[0] || a.help) return console.log(usageOf(import.meta.url));
  const set = await loadSet(a._[0]);
  const formats = a.formats ? String(a.formats).split(",") : FORMATS;
  const bad = formats.filter((f) => !FORMATS.includes(f));
  if (bad.length) throw new Error(`unknown format(s): ${bad.join(", ")} — use ${FORMATS.join(", ")}`);
  const r = buildSet(set, { out: a.out ?? path.join(a._[0], "dist"), formats, prefix: a.prefix ?? "icon-", name: a.name ?? path.basename(path.resolve(a._[0])), force: !!a.force });
  if (r.refused.length) process.exitCode = 1;
  return r;
}

if (isMain(import.meta.url))
  main().catch((e) => {
    console.error(e.message);
    process.exit(2);
  });
